'use strict';
const assert = require('assert');
const {load} = require('./dom-harness');
const sleep = ms => new Promise(r => setTimeout(r,ms));
(async()=>{
 const cx=load(), {Trio}=cx.hooks, doc=cx.document, s=Trio.state;
 s.view='conversation';s.channel='read-test';s.dmKey='';s.readOnly=false;s.operator={id:'reader'};
 s.messages=new Map([1,2,3].map(id=>[id,{id,channel:s.channel,member_id:'peer',content:'message '+id,created_at:new Date().toISOString(),recipients:[]}]));
 s.messageDomById=new Map();
 Trio.workspace.refresh=()=>{};
 const calls=[];let reject=true;
 Trio.api.post=async(path,body)=>{calls.push(body.ids);if(reject) throw Error('offline');return {ok:true};};
 Trio.conversation.seedWatermark(0,null);Trio.conversation.render();
 await sleep(300);
 const list=doc.getElementById('messages');list.getBoundingClientRect=()=>({top:0,bottom:100});
 s.messageDomById.get(1).getBoundingClientRect=()=>({top:-100,bottom:-10});
 s.messageDomById.get(2).getBoundingClientRect=()=>({top:10,bottom:70});
 s.messageDomById.get(3).getBoundingClientRect=()=>({top:80,bottom:180});
 doc.hidden=true;Trio.conversation.syncReadState({code:s.channel,last_read:0,first_unread:1});await sleep(250);
 assert.equal(calls.length,0,'hidden tabs do not mark history read');
 doc.hidden=false;Trio.conversation.syncReadState({code:s.channel,last_read:0,first_unread:1});await sleep(250);
 assert.deepEqual(Array.from(calls[0]),[2],'only reached visible message saved, not offscreen/tall history');
 assert.equal(s.lastSeenByConv[s.channel],0,'failure does not advance watermark');
 reject=false;Trio.conversation.syncReadState({code:s.channel,last_read:0,first_unread:1});await sleep(250);
 assert.deepEqual(Array.from(calls[1]),[2],'failed save remains retryable');
 assert.equal(s.lastSeenByConv[s.channel],2,'confirmed save advances watermark');
 Trio.conversation.syncReadState({code:s.channel,last_read:2,first_unread:1});await sleep(250);
 assert.equal(calls.length,2,'confirmed reads are not sent repeatedly');
 Trio.conversation.unmount();console.log('PASS visible-only, hidden-tab, failed-save retry and confirmed-read dedupe');
})().catch(e=>{console.error(e);process.exitCode=1;});
