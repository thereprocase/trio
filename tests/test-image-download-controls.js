'use strict';
const assert = require('assert');
const {load}=require('./dom-harness');
const cx=load(), H=cx.hooks;
const card=H.cardFor({id:71,member_id:'a',content:'Select these words',attachments:[{id:4,mime:'image/png',filename:'timing-diagram.png'}]});
const body=card.querySelector('.message-body');
let prevented=false;
card._listeners.contextmenu[0]({target:body,preventDefault(){prevented=true;}});
assert.strictEqual(prevented,false,'text right-click retains native Copy menu');
card._listeners.pointerdown[0]({target:body,button:0,clientX:0,clientY:0});
assert(!card.querySelector('.message-actions-menu'),'text hold does not open custom menu');
card.querySelector('.message-more')._listeners.click[0]({});
assert(card.querySelector('.message-actions-menu'),'explicit actions still reachable');
const controls=card.querySelector('.quartet-image-downloads');
assert(controls && controls.querySelector('button').textContent==='Download JPEG');
assert.strictEqual(controls.querySelector('a').download,'timing-diagram.png');
H.lightbox.open({url:'/api/attachment/4?channel=demo',alt:'timing-diagram.png'});
assert(cx.document.getElementById('trio-lightbox').querySelector('.quartet-image-downloads'));
console.log('PASS: native text selection/context menu; explicit actions; JPEG/original controls in message and lightbox');
